"""Recover the second-ability table from original rules and existing DPE data.

Reads the original generator without calling its base-stat patch or main routine.
The DPE input remains authoritative and is never modified.
"""
import argparse
import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-tools', type=Path, required=True)
    parser.add_argument('--dpe', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generator = args.source_tools.resolve() / 'abilities/build_second_abilities.py'
    spec = importlib.util.spec_from_file_location('original_second_abilities', generator)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.CFRU = str(ROOT)
    module.DPE = str(args.dpe.resolve())
    rows, excluded = module.build()
    species = module.defines(str(ROOT / 'include/constants/species.h'), 'SPECIES_')
    species_text = (ROOT / 'include/constants/species.h').read_text(encoding='utf-8')
    limit = re.search(r'^#define NUM_SPECIES\s+\((SPECIES_\w+)\s*\+\s*1\)', species_text, re.M)
    assert limit and limit[1] in species, 'Unrecognized NUM_SPECIES definition'
    species_count = species[limit[1]] + 1
    abilities = module.defines(str(ROOT / 'include/constants/abilities.h'), 'ABILITY_')
    # The current CFRU names these two existing forms by their English form names.
    renames = {'SPECIES_TATSUGIRI_RED': 'SPECIES_TATSUGIRI_DROOPY',
               'SPECIES_TATSUGIRI_YELLOW': 'SPECIES_TATSUGIRI_STRETCHY'}
    rows = [(sid, renames.get(name, name), ability, mega) for sid, name, ability, mega in rows]
    # DPE's snapshot contains later additions beyond this branch's species table.
    outside_current_table = [name for sid, name, _, _ in rows if sid >= species_count]
    rows = [row for row in rows if row[0] < species_count]
    assert rows, 'Empty second-ability table'
    assert all(a[0] < b[0] for a, b in zip(rows, rows[1:])), 'Species must be unique and sorted'
    for sid, name, ability, _ in rows:
        assert species.get(name) == sid, 'DPE/CFRU species mismatch: ' + name
        assert 0 < sid < species_count, name
        assert ability in abilities and abilities[ability] > 0, ability
    lines = ['/* Generated by scripts/generate_second_abilities.py from original rules and DPE data. */',
             '#pragma once', '', '#define SECOND_ABILITY_UNLOCK_LEVEL %d' % module.UNLOCK_LEVEL,
             '#define SECOND_ABILITY_COUNT %d' % len(rows), '',
             'static const u16 sSecondAbilities[SECOND_ABILITY_COUNT][2] =', '{']
    lines += ['\t{%s, %s}, /* %d%s */' % (name, ability, sid, ' mega' if mega else '')
              for sid, name, ability, mega in rows]
    lines += ['};', '']
    output = ROOT / 'src/Tables/second_abilities.h'
    text = '\n'.join(lines)
    if args.check:
        assert output.read_text(encoding='utf-8') == text, 'Generated header differs'
    else:
        output.write_text(text, encoding='utf-8')
        inputs = [generator, args.dpe / 'src/Base_Stats.c', args.dpe / 'src/Evolution Table.c',
                  args.dpe / 'include/species.h', ROOT / 'include/constants/species.h',
                  ROOT / 'include/constants/abilities.h']
        record = {'method': 'Original build() rules with current CFRU constants and read-only DPE input; no patch_base_stats() call.',
                  'rows': len(rows), 'excluded': excluded, 'outside_current_species_table': outside_current_table,
                  'verified_form_renames': renames,
                  'inputs': {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs},
                  'limitations': 'Does not establish DPE linked ROM data or in-game second ability behavior.'}
        (ROOT / 'audit/second_ability_header_recovery.json').write_text(
            json.dumps(record, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('Second ability header: %d sorted species rows verified.' % len(rows))


if __name__ == '__main__':
    main()
