#!/usr/bin/env python3
"""Converts the images in scripts/gfx_src into src/achievements_gfx.h
(background tiles/tilemap/palette, menu frame tiles/tilemap/palette, tier ball icons).
Requires Pillow. Run with: python3 scripts/achievements_gfx.py
The generated header is committed, so this only
needs to be re-run when the images are changed. Images come from SoulGold (graphics/pokegear/tiles.*,
graphics/achievements/menu.*, graphics/balls/*.png).
Do NOT put these images in ./graphics: the build would try to compile them with grit."""
import os, struct
from PIL import Image

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
src = os.path.join(root, 'scripts/gfx_src/')

def rgb15(r, g, b):
    return (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)

def png_pal(im):
    p = im.getpalette()[:48]
    p += [0] * (48 - len(p))
    return [rgb15(p[i*3], p[i*3+1], p[i*3+2]) for i in range(16)]

def tiles_of(im, x0=0, y0=0, w=None, h=None):
    w = w or im.size[0]; h = h or im.size[1]
    px = im.load(); out = []
    for ty in range(h // 8):
        for tx in range(w // 8):
            for y in range(8):
                v = 0
                for x in range(8):
                    v |= (px[x0 + tx*8 + x, y0 + ty*8 + y] & 0xF) << (4 * x)
                out.append(v)
    return out

def tilemap_30x20(path, stride):
    raw = open(path, 'rb').read()
    t = struct.unpack('<%dH' % (len(raw) // 2), raw)
    return [t[y*stride + x] for y in range(20) for x in range(30)]

def jasc(path):
    lines = open(path).read().split()
    n = int(lines[2]); vals = lines[3:3+n*3]
    return [rgb15(int(vals[i*3]), int(vals[i*3+1]), int(vals[i*3+2])) for i in range(n)]

def arr(name, ctype, vals, fmt, per):
    out = 'static const %s %s[] =\n{\n' % (ctype, name)
    for i in range(0, len(vals), per):
        out += '\t' + ', '.join(fmt % v for v in vals[i:i+per]) + ',\n'
    return out + '};\n\n'

bg = Image.open(src + 'bg_tiles.png'); assert bg.mode == 'P'
menu = Image.open(src + 'menu_tiles.png'); assert menu.mode == 'P'

with open(os.path.join(root, 'src/achievements_gfx.h'), 'w') as f:
    f.write('//Generated by scripts/achievements_gfx.py - do not edit\n\n')
    f.write(arr('sAchBgTiles', 'u32', tiles_of(bg), '0x%08X', 8))
    f.write(arr('sAchBgTilemap', 'u16', tilemap_30x20(src + 'bg_tilemap.bin', 30), '0x%04X', 15))
    f.write(arr('sAchBgPal', 'u16', png_pal(bg), '0x%04X', 8))
    f.write(arr('sAchMenuTiles', 'u32', tiles_of(menu), '0x%08X', 8))
    f.write(arr('sAchMenuTilemap', 'u16', tilemap_30x20(src + 'menu_tilemap.bin', 32), '0x%04X', 15))
    f.write(arr('sAchMenuPal', 'u16', jasc(src + 'menu.pal'), '0x%04X', 8))
    #Ball icons: first 16x16 frame, in the order bronze/silver/gold/platinum = poke/great/ultra/master
    tiles = []; pals = []
    for n in ('poke', 'great', 'ultra', 'master'):
        b = Image.open(src + 'ball_%s.png' % n); assert b.mode == 'P'
        t = tiles_of(b, 0, 0, 16, 16); assert len(t) == 32
        tiles += t; pals += png_pal(b)
    f.write(arr('sAchBallTiles', 'u32', tiles, '0x%08X', 8))
    f.write(arr('sAchBallPals', 'u16', pals, '0x%04X', 8))
print('ok')
