"""Recover wild held-stone table using original rules and explicit read-only inputs."""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-tools', type=Path, required=True)
    parser.add_argument('--dpe', type=Path, required=True)
    parser.add_argument('--rom', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rom = args.rom.resolve()
    data = rom.read_bytes()
    assert len(data) == 16 * 1024 * 1024 and data[0xAC:0xB0] == b'BPRJ' and data[0xBC] == 0, 'Expected BPRJ revision 0 original ROM'
    source_tools = args.source_tools.resolve()
    generator = source_tools / 'megas/build_wild_mega_stones.py'
    spec = importlib.util.spec_from_file_location('original_wild_mega_stones', generator)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.CFRU = str(ROOT)
    module.DPE = str(args.dpe.resolve())
    module.K.WILD_C = str(ROOT / 'src/Tables/wild_encounter_tables.c')
    module.K.BASE_ROM = str(rom)
    rows = module.build()
    current_species = module.defines(str(ROOT / 'include/constants/species.h'), 'SPECIES_')
    current_ids = set(current_species.values())
    items = module.defines(str(ROOT / 'include/constants/items.h'), 'ITEM_')
    assert rows and all(a[0] < b[0] for a, b in zip(rows, rows[1:])), 'Empty, duplicate or unsorted species table'
    for sid, name, iid, item, _, _ in rows:
        assert sid in current_ids and sid > 0, name
        assert items.get(item) == iid and iid > 0, item
    lines = ['/* Generated by scripts/generate_wild_mega_stones.py using original encounter/evolution rules. */',
             '#pragma once', '#define WILD_MEGA_STONE_COUNT %d' % len(rows),
             'static const u16 sWildMegaStones[WILD_MEGA_STONE_COUNT][2] =', '{']
    lines += ['\t{%d, 0x%X}, /* %s -> %s (%s) */' % (sid, iid, name, target, item)
              for sid, name, iid, item, target, _ in rows]
    lines += ['};', '']
    output = ROOT / 'src/Tables/wild_mega_stones.h'
    text = '\n'.join(lines)
    if args.check:
        assert output.read_text(encoding='utf-8') == text, 'Regenerated header differs'
    else:
        output.write_text(text, encoding='utf-8')
        inputs = [generator, source_tools / 'wild_editor/wildlib.py',
                  args.dpe / 'include/species.h', args.dpe / 'src/Evolution Table.c',
                  ROOT / 'src/Tables/wild_encounter_tables.c', ROOT / 'include/constants/species.h',
                  ROOT / 'include/constants/items.h', rom]
        record = {'method': 'Original build() with current wild C table, existing DPE evolution data and explicit original BPRJ ROM; no source/ROM input modified.',
                  'rows': len(rows), 'inputs': {str(p): hashlib.sha256(p.read_bytes()).hexdigest() for p in inputs},
                  'limitations': 'Generated numeric species/item mapping does not prove DPE linked evolution data or game held-item behavior.'}
        (ROOT / 'audit/wild_mega_stone_header_recovery.json').write_text(json.dumps(record, indent=2) + '\n', encoding='utf-8')
    print('Wild mega stone header: %d sorted species/item mappings verified.' % len(rows))


if __name__ == '__main__':
    main()
