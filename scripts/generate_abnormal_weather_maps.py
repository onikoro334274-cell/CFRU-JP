"""Recover abnormal-weather maps from preserved names and reference map order."""
import argparse
import json
from pathlib import Path

from recover_hoenn_flags import literals


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--source-tools', required=True)
    parser.add_argument('--reference', required=True)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    tools = Path(args.source_tools)
    settings = literals(tools / 'build_hoenn_scripts.py')
    base = literals(tools / 'build_hoenn_maps.py')['GMAPGROUPS_COUNT']
    groups = json.loads((Path(args.reference) / 'data/maps/map_groups.json').read_text(encoding='utf-8'))
    maps = {}
    for group, name in enumerate(groups['group_order']):
        for number, map_name in enumerate(groups[name]):
            if map_name in maps or base + group >= 256 or number >= 256:
                raise ValueError('Duplicate or out-of-range map identifier')
            maps[map_name] = (base + group, number)
    routes, caves = settings['ABN_LOCATIONS'], settings['ABN_CAVE_MAPS']
    if len(routes) != 16 or len(caves) != 9:
        raise ValueError('Unexpected weather map layout')
    lines = ['// Generated by scripts/generate_abnormal_weather_maps.py.', '#pragma once',
             '#define HOENN_ABN_TERRA_START 1', '#define HOENN_ABN_TERRA_COUNT 8',
             '#define HOENN_ABN_MARINE_START 9', '#define HOENN_ABN_MARINE_COUNT 8',
             '#define HOENN_ABN_COUNT 16']
    for name, names in [('sHoennAbnRoutes', routes), ('sHoennAbnCaveMaps', caves)]:
        lines.append('static const u8 %s[%d][2] = {' % (name, len(names)))
        lines += ['\t{%d, %d}, // %s' % (*maps[map_name], map_name) for map_name in names]
        lines.append('};')
    Path(args.output).write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('Recovered 16 weather routes and 9 protected cave maps with map-bank offset %d.' % base)


if __name__ == '__main__':
    main()
